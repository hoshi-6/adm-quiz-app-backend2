/** よく使う配色（a=本体 b=影 c=明るい部分 e=目 w=白 r=差し色 g=金属） */
export function pal(a: string, b: string, c: string, e = "#ff3b4e", extra: Palette = {}): Palette {
  return { k: K, a, b, c, e, w: "#f4f1ff", r: "#ff5d6c", g: "#c7d1dd", ...extra };
}
