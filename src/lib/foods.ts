export const FOODS: FoodEntry[] = Object.entries(RAW).flatMap(([group, { category, items }]) =>
  items
    .trim()
    .split("\n")
    .map((line) => {
      const [name, kana, unit] = line.split(",");
      return { name, kana, unit, category, group };
    }),
);

/** カタカナ→ひらがな、全角英数→半角、小文字化して比べやすくする */
export function normalize(s: string): string {
  return s
    .trim()
    .toLowerCase()
    .replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60))
    .replace(/[Ａ-Ｚａ-ｚ０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0));
}

/** 入力に合う候補を返す（前方一致を優先） */
export function searchFoods(query: string, category?: PantryCategory, limit = 8): FoodEntry[] {
  const q = normalize(query);
  if (!q) return [];
  const scored = FOODS.filter((f) => !category || f.category === category).flatMap((f) => {
    const name = normalize(f.name);
    if (name.startsWith(q) || f.kana.startsWith(q)) return [{ f, score: 0 }];
    if (name.includes(q) || f.kana.includes(q)) return [{ f, score: 1 }];
    return [];
  });
  return scored.sort((a, b) => a.score - b.score).slice(0, limit).map((x) => x.f);
}
